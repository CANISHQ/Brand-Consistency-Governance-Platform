import threading


class Store:
    """Storage interface. Documents are plain dicts, the same shapes the frontend uses."""

    lock = threading.RLock()

    def get_profile(self) -> dict: ...
    def get_changelog(self) -> list: ...
    def save_profile(self, profile: dict, entry: dict) -> None: ...
    def list_submissions(self) -> list: ...
    def get_submission(self, sid: str) -> dict | None: ...
    def put_submission(self, sub: dict) -> None: ...
    def next_submission_id(self) -> str: ...
    def reset(self, profile: dict, changelog: list, submissions: list) -> None: ...
    def is_empty(self) -> bool: ...


def seed_if_empty(store: Store, loader):
    if store.is_empty():
        store.reset(*loader())
